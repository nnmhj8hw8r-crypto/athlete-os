with open(SRC + '/food.csv', encoding='utf-8') as f:
    desc = {int(r['fdc_id']): r['description'] for r in csv.DictReader(f)}
missing = [i for i in PICK if i not in desc]
if missing:
    sys.exit(f'missing fdc ids: {missing}')

want = {1003: 'protein', 1004: 'fat', 1005: 'carbs', 1008: 'kcal', 2047: 'kcal_a', 2048: 'kcal_s'}
vals = {i: {} for i in PICK}
with open(SRC + '/food_nutrient.csv', encoding='utf-8') as f:
    for r in csv.DictReader(f):
        fid = int(r['fdc_id'])
        if fid in vals:
            nid = int(r['nutrient_id'])
            if nid in want and r['amount'] != '':
                vals[fid][want[nid]] = float(r['amount'])

out = []
for fid, ru in PICK.items():
    v = vals[fid]
    kcal = v.get('kcal', v.get('kcal_s', v.get('kcal_a')))
    if kcal is None or any(k not in v for k in ('protein', 'fat', 'carbs')):
        sys.exit(f'incomplete nutrients for {fid} {desc[fid]}: {v}')
    out.append({
        'id': f'usda:{fid}',
        'name': ru,
        'source': desc[fid],
        'per100': {k: round(x, 1) for k, x in (('kcal', kcal), ('protein', v['protein']), ('fat', v['fat']), ('carbs', v['carbs']))},
    })

body = ',\n'.join('  ' + json.dumps(o, ensure_ascii=False) for o in out)
ts = f'''// СГЕНЕРИРОВАНО скриптом из USDA FoodData Central, SR Legacy (апрель 2018), лицензия CC0.
// Значения — на 100 г съедобной части (для напитков тоже на 100 г). Русские названия — перевод
// описания USDA (поле source); цифры не редактировать вручную.
// https://fdc.nal.usda.gov/
export interface ReferenceFood {{
  id: string;
  name: string;
  /** Исходное описание продукта в USDA FoodData Central. */
  source: string;
  per100: {{ kcal: number; protein: number; fat: number; carbs: number }};
}}

export const REFERENCE_FOODS: readonly ReferenceFood[] = [
{body},
];
'''
with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
    f.write(ts)
print(f'wrote {len(out)} foods')
