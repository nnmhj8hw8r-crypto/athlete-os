// Данные — только то, что сказано в консенсусе IOC (Maughan 2018, PMID 29540367, PMC5867441); от себя ничего не добавлено.

export const PERSONAL_MODE_KEY = 'personalMode';

export interface PersonalMode {
  enabled: boolean;
  acceptedAt: string;
}

/** Режим включён, только если есть дата согласия: битое значение в копии = выключено. */
export function normalizePersonalMode(raw: unknown): PersonalMode | null {
  const v = raw as Partial<PersonalMode> | null | undefined;
  return v?.enabled === true && typeof v.acceptedAt === 'string' ? { enabled: true, acceptedAt: v.acceptedAt } : null;
}

export type RiskLevel = 'низкий' | 'умеренный' | 'высокий';

export interface SupplementFact {
  id: string;
  name: string;
  /** Для чего (по консенсусу). */
  effect: string;
  /** Схема, как её описывает консенсус IOC — ориентир для разговора со специалистом, не назначение. */
  protocol: string;
  /** Уровень доказательности словами консенсуса. */
  evidence: string;
  risk: RiskLevel;
  /** Побочные эффекты и ограничения из того же источника. */
  cautions: string;
}

